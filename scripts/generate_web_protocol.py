#!/usr/bin/env python3
"""从后端 Pydantic 协议生成 JSON Schema 和前端 TypeScript 类型。"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from tcode_agent.protocol.models import protocol_schema_document
from tcode_agent.protocol.v2 import protocol_schema_document as protocol_v2_schema_document


DEFAULT_SCHEMA_PATH = REPO_ROOT / "tcode_agent/protocol/schema/web-protocol-v1.schema.json"
DEFAULT_TYPES_PATH = REPO_ROOT / "web/src/api/generated/protocol.ts"
V2_SCHEMA_PATH = REPO_ROOT / "tcode_agent/protocol/v2/schema/protocol.schema.json"
V2_TYPES_PATH = REPO_ROOT / "web/src/protocol/generated.ts"


def _literal(value: Any) -> str:
    if value is None:
        return "null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return str(value)


def _property_name(value: str) -> str:
    return value if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", value) else json.dumps(value)


def _type_expression(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return _literal(schema["const"])
    if "enum" in schema:
        values = schema.get("enum") or []
        return " | ".join(_literal(value) for value in values) or "never"
    for union_key in ("anyOf", "oneOf"):
        if union_key in schema:
            parts: list[str] = []
            for item in schema[union_key]:
                rendered = _type_expression(item)
                if rendered not in parts:
                    parts.append(rendered)
            return " | ".join(parts) or "unknown"
    if "allOf" in schema:
        return " & ".join(_type_expression(item) for item in schema["allOf"])

    schema_type = schema.get("type")
    if isinstance(schema_type, list):
        return " | ".join(_type_expression({"type": value}) for value in schema_type)
    if schema_type == "string":
        return "string"
    if schema_type in {"integer", "number"}:
        return "number"
    if schema_type == "boolean":
        return "boolean"
    if schema_type == "null":
        return "null"
    if schema_type == "array":
        item_type = _type_expression(schema.get("items") or {})
        return f"Array<{item_type}>"
    if schema_type == "object" or "properties" in schema or "additionalProperties" in schema:
        properties = schema.get("properties") or {}
        required = set(schema.get("required") or [])
        if properties:
            fields = []
            for name, field_schema in properties.items():
                optional = "" if name in required else "?"
                fields.append(
                    f"{_property_name(name)}{optional}: {_type_expression(field_schema)};"
                )
            return "{ " + " ".join(fields) + " }"
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            return f"Record<string, {_type_expression(additional)}>"
        if additional is True:
            return "Record<string, unknown>"
        return "Record<string, never>"
    return "unknown"


def render_types(
    document: dict[str, Any],
    *,
    version_constant: str = "WEB_PROTOCOL_VERSION",
) -> str:
    definitions = document.get("$defs") or {}
    exported = document.get("x-exported-models") or []
    lines = [
        "// Generated by scripts/generate_web_protocol.py; do not edit manually.",
        f"// Contract: {document['x-contract-id']}@{document['x-protocol-version']}",
        "",
        f"export const {version_constant} = {json.dumps(document['x-protocol-version'])} as const;",
        "",
    ]
    for name in exported:
        schema = definitions[name]
        if schema.get("type") == "object" and schema.get("properties"):
            required = set(schema.get("required") or [])
            lines.append(f"export interface {name} {{")
            for field_name, field_schema in schema["properties"].items():
                optional = "" if field_name in required else "?"
                lines.append(
                    f"  {_property_name(field_name)}{optional}: {_type_expression(field_schema)};"
                )
            if schema.get("additionalProperties") is True:
                lines.append("  [key: string]: unknown;")
            lines.append("}")
        else:
            lines.append(f"export type {name} = {_type_expression(schema)};")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_schema(document: dict[str, Any]) -> str:
    return json.dumps(document, ensure_ascii=False, indent=2) + "\n"


def generate(*, check: bool = False) -> bool:
    document = protocol_schema_document()
    v2_document = protocol_v2_schema_document()
    outputs = {
        DEFAULT_SCHEMA_PATH: render_schema(document),
        DEFAULT_TYPES_PATH: render_types(document),
        V2_SCHEMA_PATH: render_schema(v2_document),
        V2_TYPES_PATH: render_types(
            v2_document,
            version_constant="AGENT_EVENTS_PROTOCOL_VERSION",
        ),
    }
    stale: list[Path] = []
    for path, content in outputs.items():
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        stale.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")

    if stale and check:
        print("协议生成文件已过期: " + ", ".join(str(path.relative_to(REPO_ROOT)) for path in stale))
        print("请运行: python scripts/generate_web_protocol.py")
        return False
    for path in stale:
        print(f"generated {path.relative_to(REPO_ROOT)}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="只检查生成文件是否最新")
    args = parser.parse_args()
    return 0 if generate(check=args.check) else 1


if __name__ == "__main__":
    raise SystemExit(main())
