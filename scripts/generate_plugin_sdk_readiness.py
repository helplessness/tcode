#!/usr/bin/env python3
"""生成 Plugin SDK v1 就绪度契约及人工可读报告。"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from tcode_agent.runtime.sdk_readiness import plugin_sdk_v1_readiness_document


DEFAULT_CONTRACT_PATH = Path(
    "tcode_agent/plugins/contracts/plugin_sdk_v1_readiness.json"
)
DEFAULT_JSON_PATH = Path("build/dsh/contracts/plugin-sdk-v1-readiness.json")
DEFAULT_MARKDOWN_PATH = Path("build/dsh/contracts/plugin-sdk-v1-readiness.md")


def render_json(document: dict[str, Any]) -> str:
    """把 SDK 就绪度报告渲染为稳定 JSON。"""

    return json.dumps(document, ensure_ascii=False, indent=2) + "\n"


def render_markdown(document: dict[str, Any]) -> str:
    """把 SDK 就绪度报告渲染为便于人工审核的 Markdown。"""

    targets = document["targets"]
    reference = document["reference_plugins"]
    lines = [
        "# Plugin SDK v1 Readiness Audit",
        "",
        "> Generated by `scripts/generate_plugin_sdk_readiness.py`; do not edit manually.",
        "",
        f"- Contract: `{document['contract_id']}`",
        f"- Status: `{document['status']}`",
        f"- Ready to freeze v1: `{str(document['ready_to_freeze_v1']).lower()}`",
        f"- Decision: `{document['decision']}`",
        f"- Production behavior changed: `{str(document['production_behavior_changed']).lower()}`",
        f"- Release scope: `{document['release_scope']}`",
        "",
        "## Gate summary",
        "",
        "| Gate | Status | Required | Summary | Blockers |",
        "| --- | --- | --- | --- | --- |",
    ]
    for gate in document["gates"]:
        blockers = "<br>".join(gate["blockers"]) or "—"
        lines.append(
            f"| `{gate['id']}` | `{gate['status']}` | "
            f"`{str(gate['required_for_freeze']).lower()}` | {gate['summary']} | {blockers} |"
        )
    lines.extend(
        [
            "",
            "## Official reference plugin coverage",
            "",
            f"- Repository plugins scanned: `{reference['scanned_count']}`",
            f"- Public-SDK-only reference plugins: `{reference['qualified_count']}` / "
            f"`{targets['official_reference_plugins']}`",
            f"- Required references per frozen interface: "
            f"`{targets['references_per_frozen_interface']}`",
            "",
            "| Surface | Current references | Missing |",
            "| --- | ---: | ---: |",
        ]
    )
    for surface in targets["public_surfaces"]:
        count = reference["surface_coverage"][surface]
        missing = reference["surface_deficits"].get(surface, 0)
        lines.append(f"| `{surface}` | {count} | {missing} |")
    lines.extend(
        [
            "",
            "### Scanned packages",
            "",
            "| Plugin | Public SDK only | Reference qualified | Surfaces | Private runtime imports |",
            "| --- | --- | --- | --- | --- |",
        ]
    )
    for package in reference["packages"]:
        imports = "<br>".join(package["private_runtime_imports"]) or "—"
        surfaces = ", ".join(package["used_public_surfaces"]) or "—"
        lines.append(
            f"| `{package['name']}` | `{str(package['public_sdk_only']).lower()}` | "
            f"`{str(package['reference_qualified']).lower()}` | {surfaces} | {imports} |"
        )
    lines.extend(
        [
            "",
            "## Freeze blockers",
            "",
            *[f"- `{gate_id}`" for gate_id in document["required_blockers"]],
            "",
            "> This report is a repository-static audit. A passing static gate does not replace live canary, release, or rollback evidence.",
        ]
    )
    return "\n".join(lines).rstrip() + "\n"


def generate(
    *,
    contract_path: Path = DEFAULT_CONTRACT_PATH,
    json_path: Path = DEFAULT_JSON_PATH,
    markdown_path: Path = DEFAULT_MARKDOWN_PATH,
    check: bool = False,
) -> bool:
    """生成或校验 SDK 就绪度文件，并返回是否为最新状态。"""

    document = plugin_sdk_v1_readiness_document(REPO_ROOT)
    outputs = {
        contract_path: render_json(document),
        json_path: render_json(document),
        markdown_path: render_markdown(document),
    }
    stale: list[Path] = []
    for path, content in outputs.items():
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        stale.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        if check:
            print("stale SDK readiness report: " + ", ".join(str(path) for path in stale))
            return False
        for path in stale:
            print(f"generated {path}")
    return True


def main() -> int:
    """解析命令行参数并执行 SDK 就绪度生成。"""

    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    return 0 if generate(check=args.check) else 1


if __name__ == "__main__":
    raise SystemExit(main())
