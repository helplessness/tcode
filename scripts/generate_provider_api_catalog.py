#!/usr/bin/env python3
"""生成不向插件授权的 Provider API v1 内部边界目录。"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from tcode_agent.runtime.provider_api import provider_api_catalog_document


DEFAULT_CONTRACT_PATH = Path(
    "tcode_agent/plugins/contracts/provider_api_internal_v1.json"
)
DEFAULT_JSON_PATH = Path("build/dsh/contracts/provider-api-internal-v1.json")
DEFAULT_MARKDOWN_PATH = Path("build/dsh/contracts/provider-api-internal-v1.md")


def render_json(document: dict[str, Any]) -> str:
    """把 Provider 内部契约渲染为稳定 JSON。"""

    return json.dumps(document, ensure_ascii=False, indent=2) + "\n"


def render_markdown(document: dict[str, Any]) -> str:
    """把 Provider 内部契约渲染为便于人工审核的 Markdown。"""

    lines = [
        "# Provider API Internal v1 Catalog",
        "",
        "> Generated by `scripts/generate_provider_api_catalog.py`; do not edit manually.",
        "",
        f"- Contract: `{document['contract_id']}`",
        f"- Version: `{document['api_version']}`",
        f"- Status: `{document['status']}`",
        f"- PluginContext exposed: `{str(document['plugin_context_exposed']).lower()}`",
        f"- Production consumer switched: `{str(document['production_consumer_switched']).lower()}`",
        f"- Default plugin invocation: `{document['default_plugin_invocation']}`",
        "",
        "| Capability | ServiceKey | Phase | Exposure | Adapter | Operations |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for item in document["capabilities"]:
        operations = ", ".join(
            f"{operation['name']} ("
            + ", ".join(
                f"`{permission}`"
                for permission in [
                    operation["permission"],
                    *operation["additional_permissions"],
                ]
            )
            + ")"
            for operation in item["operations"]
        )
        lines.append(
            f"| `{item['id']}` | `{item['service_key']}` | `{item['phase']}` | "
            f"`{item['exposure']}` | `{item['adapter_status']}` | {operations} |"
        )
    lines.extend(["", "## Blockers and kernel invariants", ""])
    for item in document["capabilities"]:
        lines.extend(
            [
                f"### `{item['id']}`",
                "",
                "Blockers:",
                "",
                *[f"- {value}" for value in item["blockers"]],
                "",
                "Kernel invariants:",
                "",
                *[f"- {value}" for value in item["kernel_invariants"]],
                "",
            ]
        )
    return "\n".join(lines).rstrip() + "\n"


def generate(
    *,
    contract_path: Path = DEFAULT_CONTRACT_PATH,
    json_path: Path = DEFAULT_JSON_PATH,
    markdown_path: Path = DEFAULT_MARKDOWN_PATH,
    check: bool = False,
) -> bool:
    """生成或校验 Provider 内部契约文件，并返回是否为最新状态。"""

    document = provider_api_catalog_document()
    outputs = {
        contract_path: render_json(document),
        json_path: render_json(document),
        markdown_path: render_markdown(document),
    }
    stale: list[Path] = []
    for path, content in outputs.items():
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        stale.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        if check:
            print("stale provider catalog: " + ", ".join(str(path) for path in stale))
            return False
        for path in stale:
            print(f"generated {path}")
    return True


def main() -> int:
    """解析命令行参数并执行 Provider 契约生成。"""

    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    return 0 if generate(check=args.check) else 1


if __name__ == "__main__":
    raise SystemExit(main())
